CREATE DATABASE LIGHTNING;
USE LIGHTNING;

-- TABLE 1 - OBSERVATION_STATIONS
CREATE TABLE OBSERVATION_STATIONS (
    STATION_ID INT PRIMARY KEY,
    STATION_NAME VARCHAR(100) NOT NULL,
    LATITUDE DECIMAL(9,6) NOT NULL,
    LONGITUDE DECIMAL(9,6) NOT NULL,
    ALTITUDE_m DECIMAL(8,2) NOT NULL,
    COUNTRY VARCHAR(50)
);

-- TABLE 2 - LIGHTNING_EVENTS
CREATE TABLE LIGHTNING_EVENTS (
    EVENT_ID INT PRIMARY KEY,
    STATION_ID INT NOT NULL,
    EVENT_DATE_TIME DATETIME NOT NULL,
    LIGHTNING_TYPE ENUM('IC','CG','CC') NOT NULL,
    PEAK_CURRENT_kA DECIMAL(8,3),
    DURATION_us DECIMAL(10,3),

        FOREIGN KEY (STATION_ID)
        REFERENCES OBSERVATION_STATIONS(STATION_ID)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

-- TABLE 3 - LIGHTNING_CHANNELS
CREATE TABLE LIGHTNING_CHANNELS (
    CHANNEL_ID INT PRIMARY KEY,
    EVENT_ID INT NOT NULL,
    CHANNEL_TYPE ENUM('HORIZONTAL','TORTUOUS','VERTICAL') NOT NULL,
    CHANNEL_LENGTH_m DECIMAL(10,2),
    PROPAGATION_VELOCITY_m_s DECIMAL(15,2),
    PEAK_CURRENT_kA DECIMAL(8,3),

        FOREIGN KEY (EVENT_ID)
        REFERENCES LIGHTNING_EVENTS(EVENT_ID)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

-- TABLE 4 - CHANNEL_POINTS
CREATE TABLE CHANNEL_POINTS (
    CHANNEL_POINT_ID INT PRIMARY KEY,
    CHANNEL_ID INT NOT NULL,
    POINT_INDEX INT NOT NULL,
    X_m DECIMAL(12,6),
    Y_m DECIMAL(12,6),
    Z_m DECIMAL(12,6),
    SEGMENT_LENGTH_m DECIMAL(12,6),

        FOREIGN KEY (CHANNEL_ID)
        REFERENCES LIGHTNING_CHANNELS(CHANNEL_ID)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

-- TABLE 5 - LIGHTNING_MEASUREMENTS
CREATE TABLE LIGHTNING_MEASUREMENTS (
    MEASUREMENT_ID INT PRIMARY KEY,
    EVENT_ID INT NOT NULL,
    OBSERVATION_ALTITUDE_km DECIMAL(6,2) NOT NULL,
    ELECTRIC_FIELD_V_m DECIMAL(12,6),
    MAGNETIC_FIELD_A_m DECIMAL(12,6),
    FREQUENCY_Hz DECIMAL(12,2),

        FOREIGN KEY (EVENT_ID)
        REFERENCES LIGHTNING_EVENTS(EVENT_ID)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

-- TABLE 6 - ATMOSPHERIC_CONDS
CREATE TABLE ATMOSPHERIC_CONDS (
    COND_ID INT PRIMARY KEY,
    EVENT_ID INT NOT NULL,
    TEMP_C DECIMAL(6,2),
    PRESSURE_hPa DECIMAL(8,2),
    HUMIDITY_PERCENT DECIMAL(5,2),
    WIND_SPEED_m_s DECIMAL(6,2),

        FOREIGN KEY (EVENT_ID)
        REFERENCES LIGHTNING_EVENTS(EVENT_ID)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

