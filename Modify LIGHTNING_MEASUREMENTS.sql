USE LIGHTNING;

SELECT
    EVENT_ID,
    OBSERVATION_ALTITUDE_km,
    TIME_us,
    COUNT(*) AS duplicate_count
FROM LIGHTNING_MEASUREMENTS
GROUP BY
    EVENT_ID,
    OBSERVATION_ALTITUDE_km,
    TIME_us
HAVING COUNT(*) > 1;

ALTER TABLE LIGHTNING_MEASUREMENTS
ADD CONSTRAINT uq_measurement_identity
UNIQUE (
    EVENT_ID,
    OBSERVATION_ALTITUDE_km,
    TIME_us
);

DESC LIGHTNING_MEASUREMENTS;