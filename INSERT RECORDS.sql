-- EVENTS LINKED TO NON-EXISTENT STATIONS
SELECT
    le.EVENT_ID,
    le.STATION_ID
FROM lightning_events AS le
LEFT JOIN observation_stations AS os
    ON le.STATION_ID = os.STATION_ID
WHERE os.STATION_ID IS NULL;


-- ORPHANED RECORDS

SELECT 'Events without stations' AS CHECK_NAME, COUNT(*) AS PROBLEM_COUNT
FROM lightning_events le
LEFT JOIN observation_stations os
    ON le.STATION_ID = os.STATION_ID
WHERE os.STATION_ID IS NULL

UNION ALL

SELECT 'Channels without events', COUNT(*)
FROM lightning_channels lc
LEFT JOIN lightning_events le
    ON lc.EVENT_ID = le.EVENT_ID
WHERE le.EVENT_ID IS NULL

UNION ALL

SELECT 'Measurements without events', COUNT(*)
FROM lightning_measurements lm
LEFT JOIN lightning_events le
    ON lm.EVENT_ID = le.EVENT_ID
WHERE le.EVENT_ID IS NULL

UNION ALL

SELECT 'Atmospheric conditions without events', COUNT(*)
FROM atmospheric_conds ac
LEFT JOIN lightning_events le
    ON ac.EVENT_ID = le.EVENT_ID
WHERE le.EVENT_ID IS NULL

UNION ALL

SELECT 'Channel points without channels', COUNT(*)
FROM channel_points cp
LEFT JOIN lightning_channels lc
    ON cp.CHANNEL_ID = lc.CHANNEL_ID
WHERE lc.CHANNEL_ID IS NULL;